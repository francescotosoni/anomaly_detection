"""
Unblock the Gather operator in an Edge Impulse Arduino library.

WHY: in the Edge Impulse SDK, `MicroMutableOpResolver::AddGather()`, the
declaration of `Register_GATHER()` and the whole of `kernels/gather.cpp` are
wrapped in `#ifndef TF_LITE_STATIC_MEMORY`. In an ESP32 build that macro ends up
defined (it is not in the Nano's mbed build), so all three disappear — yet the
resolver generated by Edge Impulse still calls `AddGather()`, and compilation
fails with:

    error: 'class tflite::MicroMutableOpResolver<N>' has no member named 'AddGather'

Unblocking them is safe: `gather.cpp` only uses the standard `micro_context` API
and `ParseGather` is not guarded at all, so the code compiles fine in
static-memory mode too. The guard is a precaution inherited from upstream, not a
real constraint for this kernel.

The patch must be reapplied after EVERY re-export of the library from Edge
Impulse. The script is idempotent: if the library is already patched it does
nothing.

USAGE:
  python utils/patch_ei_gather.py --lib ICE_s3_MLP_inferencing
  python utils/patch_ei_gather.py --lib <full path>
  python utils/patch_ei_gather.py --all      # every library that needs it
"""

import os
import re
import sys
import glob
import argparse

SKETCHBOOK_CANDIDATES = [
    r'%USERPROFILE%\OneDrive - Università degli Studi di Verona\Documenti\Arduino',
    r'%USERPROFILE%\Documents\Arduino',
    r'%USERPROFILE%\OneDrive\Documenti\Arduino',
    r'%USERPROFILE%\Documenti\Arduino',
]

MARK = 'PATCH ICE'

# (relative path, text to replace, replacement)
PATCHES = [
    (
        'src/edge-impulse-sdk/tensorflow/lite/micro/micro_mutable_op_resolver.h',
        "#ifndef TF_LITE_STATIC_MEMORY\n"
        "  TfLiteStatus AddGather() {\n"
        "    return AddBuiltin(BuiltinOperator_GATHER, tflite::Register_GATHER(),\n"
        "                      ParseGather);\n"
        "  }\n"
        "#endif",

        "  // PATCH ICE: removed the `#ifndef TF_LITE_STATIC_MEMORY` around this method.\n"
        "  // In an ESP32 build that macro ends up defined (not so in the Nano's mbed\n"
        "  // build), so AddGather() disappeared while the resolver generated by Edge\n"
        "  // Impulse still calls it -> compile error. Kernel and parser both exist and\n"
        "  // use no API reserved to dynamic mode, so unblocking it is safe.\n"
        "  // Regenerated by utils/patch_ei_gather.py after every Edge Impulse export.\n"
        "  TfLiteStatus AddGather() {\n"
        "    return AddBuiltin(BuiltinOperator_GATHER, tflite::Register_GATHER(),\n"
        "                      ParseGather);\n"
        "  }",
    ),
    (
        'src/edge-impulse-sdk/tensorflow/lite/micro/kernels/micro_ops.h',
        "#ifndef TF_LITE_STATIC_MEMORY\n"
        "TfLiteRegistration Register_GATHER();\n"
        "#endif // TF_LITE_STATIC_MEMORY",

        "// PATCH ICE: TF_LITE_STATIC_MEMORY guard removed, see micro_mutable_op_resolver.h\n"
        "TfLiteRegistration Register_GATHER();",
    ),
    (
        'src/edge-impulse-sdk/tensorflow/lite/micro/kernels/gather.cpp',
        "==============================================================================*/\n"
        "#ifndef TF_LITE_STATIC_MEMORY\n",

        "==============================================================================*/\n"
        "// PATCH ICE: TF_LITE_STATIC_MEMORY guard removed (here and at the end of the\n"
        "// file), see micro_mutable_op_resolver.h. This kernel only uses the standard\n"
        "// micro_context API, so it compiles in static-memory mode as well.\n",
    ),
    (
        'src/edge-impulse-sdk/tensorflow/lite/micro/kernels/gather.cpp',
        "}  // namespace tflite\n#endif // TF_LITE_STATIC_MEMORY",
        "}  // namespace tflite",
    ),
]


def find_libraries_dir():
    for c in SKETCHBOOK_CANDIDATES:
        p = os.path.join(os.path.expandvars(c), 'libraries')
        if os.path.isdir(p):
            return p
    return None


def needs_patch(lib):
    """True if the generated resolver calls AddGather but the method is still guarded."""
    res = os.path.join(lib, 'src', 'tflite-model', 'tflite-resolver.h')
    if not os.path.isfile(res):
        return False
    if 'AddGather()' not in open(res, encoding='utf-8', errors='replace').read():
        return False
    hdr = os.path.join(lib, PATCHES[0][0])
    if not os.path.isfile(hdr):
        return False
    return MARK not in open(hdr, encoding='utf-8', errors='replace').read()


def patch(lib):
    name = os.path.basename(lib)
    res = os.path.join(lib, 'src', 'tflite-model', 'tflite-resolver.h')
    if not os.path.isfile(res):
        print(f"  [--] {name}: does not look like an Edge Impulse library")
        return False
    if 'AddGather()' not in open(res, encoding='utf-8', errors='replace').read():
        print(f"  [--] {name}: does not use Gather, no patch needed")
        return False

    applied = 0
    for rel, old, new in PATCHES:
        path = os.path.join(lib, rel)
        if not os.path.isfile(path):
            print(f"  [X ] {name}: missing {rel}")
            return False
        txt = open(path, encoding='utf-8', errors='replace').read()
        # Normalise line endings: libraries extracted from a zip may use CRLF.
        nl = '\r\n' if '\r\n' in txt else '\n'
        flat = txt.replace('\r\n', '\n')
        if old in flat:
            flat = flat.replace(old, new, 1)
            open(path, 'w', encoding='utf-8', newline=nl).write(flat)
            applied += 1
        elif MARK in flat:
            pass          # already applied
        else:
            print(f"  [X ] {name}: block not found in {os.path.basename(rel)} — "
                  f"the SDK may have changed, check by hand")
            return False

    if applied:
        print(f"  [OK] {name}: {applied} blocks unblocked")
    else:
        print(f"  [==] {name}: already patched")
    return True


def main():
    ap = argparse.ArgumentParser(description="Unblock the Gather op in an Edge Impulse library")
    ap.add_argument('--lib', help="Folder name under libraries/, or a full path")
    ap.add_argument('--all', action='store_true', help="Patch every library that needs it")
    ap.add_argument('--libraries-dir', default=None)
    args = ap.parse_args()

    libs_dir = args.libraries_dir or find_libraries_dir()
    if not libs_dir:
        print("[X] libraries/ folder not found. Pass --libraries-dir.")
        sys.exit(1)

    if args.all:
        targets = [d for d in sorted(glob.glob(os.path.join(libs_dir, '*')))
                   if os.path.isdir(d) and needs_patch(d)]
        if not targets:
            print("  No library needs patching.")
            sys.exit(0)
    elif args.lib:
        targets = [args.lib if os.path.isdir(args.lib) else os.path.join(libs_dir, args.lib)]
    else:
        print("[X] --lib or --all required")
        sys.exit(1)

    print(f"  libraries/: {libs_dir}\n")
    ok = True
    for t in targets:
        if not os.path.isdir(t):
            print(f"  [X ] not found: {t}")
            ok = False
            continue
        ok = patch(t) and ok

    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
